from typing import Protocol
from uuid import UUID

from app.application.services.feed_page import FeedCandidates, FeedSession, FeedWindow


class PersonalizedFeedStore(Protocol):
    async def start(self, user_id: UUID) -> FeedSession: ...
    async def session(self, session_id: UUID) -> FeedSession: ...
    async def window(self, session: FeedSession, index: int) -> FeedWindow | None: ...
    async def save_window(
        self, session: FeedSession, index: int, window: FeedWindow
    ) -> FeedWindow: ...
    async def candidates(self, user_id: UUID, score: float, identifier: str) -> FeedCandidates: ...
    async def visible(self, user_id: UUID, ids: tuple[UUID, ...]) -> set[UUID]: ...


class FeedAudience(Protocol):
    async def eligible_authors(self, user_id: UUID, authors: tuple[UUID, ...]) -> set[UUID]: ...
