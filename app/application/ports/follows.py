from typing import Any, Protocol
from uuid import UUID

from app.application.services.follow_job import FollowJob, FollowSnapshot
from app.domain.entities import User


class FollowStore(Protocol):
    async def validate_users(self, follower_id: UUID, followed_id: UUID) -> tuple[User, User]: ...
    async def enqueue(self, job: FollowJob, keyed: bool) -> FollowJob: ...
    async def get(self, operation_id: UUID) -> FollowJob: ...
    async def save(self, job: FollowJob) -> None: ...
    async def pending(self) -> list[FollowJob]: ...
    async def active_pair(self, follower_id: UUID, followed_id: UUID) -> FollowJob | None: ...
    async def post_catalog(self, author_id: UUID) -> list[UUID]: ...
    async def recent_candidates(self, author_id: UUID) -> dict[str, float]: ...
    async def retry(self, operation_id: UUID) -> FollowJob: ...


class FollowGraph(Protocol):
    async def follow_snapshot(self, follower_id: UUID, followed_id: UUID) -> dict[str, Any]: ...
    async def set_follow_state(self, job: FollowJob) -> None: ...
    async def restore_follow(self, job: FollowJob) -> None: ...
    async def follow_counts(self, user_id: UUID) -> dict[str, int]: ...
    async def incoming_requests(self, user_id: UUID) -> tuple[UUID, ...]: ...


class FollowViews(Protocol):
    async def begin(self, job: FollowJob) -> FollowSnapshot: ...
    async def set_counts(self, counts: dict[str, dict[str, int]]) -> None: ...
    async def initialize_counts(self, user_id: UUID, counts: dict[str, int]) -> None: ...
    async def counts(self, user_id: UUID) -> dict[str, int]: ...
    async def apply_batch(self, job: FollowJob, posts: dict[str, float]) -> None: ...
    async def finish(self, job: FollowJob, restore: bool = False) -> None: ...
